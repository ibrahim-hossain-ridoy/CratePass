export const BATTERY_FIELDS: readonly BatteryFieldDefinition[] =
  RAW_OFFICIAL_POINTS.map((seed) => ({
    ...seed,
    required: seed.requiredFor.includes("LMT"),
  }));

/** Official 71 numbered points (excluding the private catch-all field). */
export const OFFICIAL_71_FIELDS: readonly BatteryFieldDefinition[] =
  BATTERY_FIELDS.filter((f) => typeof f.pointNumber === "number");

/** Static fields (Points 1–50 + additional_information) eligible for PDF extraction & manual input. */
export const STATIC_BATTERY_FIELDS: readonly BatteryFieldDefinition[] =
  BATTERY_FIELDS.filter((f) => f.source === "static");

/** Dynamic in-service BMS telemetry fields (Points 51–71) excluded from PDF extraction & never blocking publish. */
export const DYNAMIC_BMS_FIELDS: readonly BatteryFieldDefinition[] =
  BATTERY_FIELDS.filter((f) => f.source === "dynamic");

export const BATTERY_FIELD_MAP: Readonly<
  Record<string, BatteryFieldDefinition>
> = Object.fromEntries(BATTERY_FIELDS.map((field) => [field.key, field]));

export function isValidBatteryCategory(val: unknown): val is BatteryCategory {
  return val === "LMT" || val === "EV" || val === "industrial";
}

export function normalizeBatteryCategory(val: unknown): BatteryCategory {
  return isValidBatteryCategory(val) ? val : "LMT";
}

export function isFieldRequiredForCategory(
  field: BatteryFieldDefinition,
  category: BatteryCategory,
): boolean {
  return field.requiredFor.includes(category);
}

/** Only static fields required for the chosen category can count as missing-required for PDF/manual completion. */
export function isStaticBlockingFieldForCategory(
  field: BatteryFieldDefinition,
  category: BatteryCategory,
): boolean {
  return field.source === "static" && field.requiredFor.includes(category);
}

export function getRequiredFieldsForCategory(
  category: BatteryCategory,
): BatteryFieldDefinition[] {
  return OFFICIAL_71_FIELDS.filter((field) =>
    isFieldRequiredForCategory(field, category),
  );
}

export function getStaticRequiredFieldsForCategory(
  category: BatteryCategory,
): BatteryFieldDefinition[] {
  return STATIC_BATTERY_FIELDS.filter((field) =>
    isStaticBlockingFieldForCategory(field, category),
  );
}
